import crypto from "node:crypto";
import type { Account as LedgerAccount } from "../contracts/types.ts";
import type { Store } from "../persistence/store.ts";
import { serialTx } from "../persistence/store.ts";
import type { SimTruthRepository } from "../persistence/repos/truth.ts";
import type { Account, Pattern } from "./types.ts";

// Synthetic UPI traffic generator over a FUNDED ledger. It never moves money
// itself: it only proposes payment requests; the engine submits every one of
// them to the single admission gate (AccountRepository.admit), which checks
// active holds and balances at execution time.
//
//   base load        — person→merchant, person→person and merchant→person
//                      settlements (so everyday balances do not drain)
//   fanout_layering  — victim pays a scam account; the money is blasted down
//                      2 layers of mules and converges on cash-out accounts
//   circular_routing — a closed loop of accounts cycles decaying amounts
//   smurfing         — many funded mule senders send just-under-₹10k amounts
//                      to one aggregator
//
// Every scenario records its mule accounts as ground truth in `sim_truth`
// (via SimTruthRepository) so live precision/recall can be measured. Case
// tracing, analysis and APIs never read that table.

const FIRST = ["rahul", "priya", "amit", "sneha", "vikram", "ananya", "rohan", "kavya", "arjun", "isha", "manish", "pooja", "sandeep", "neha", "kiran", "divya", "suresh", "meera", "aakash", "ritu"];
const LAST = ["sharma", "verma", "patel", "iyer", "reddy", "singh", "gupta", "nair", "das", "joshi", "kulkarni", "mehta", "bose", "rao", "malhotra"];
const BANKS = ["oksbi", "okhdfcbank", "okicici", "okaxis", "ybl", "paytm", "ibl", "apl"];
const MERCHANTS = ["swiggy", "zomato", "bigbasket", "jiomart", "irctc", "redbus", "bookmyshow", "flipkart", "meesho", "blinkit", "zepto", "phonepe.rech", "airtel.bill", "tataneu", "myntra"];

const DAY_MS = 86_400_000;
/** Share of base load that is merchant→person settlement (balances ≈ stationary). */
const SETTLEMENT_SHARE = 0.38;
const PERSON_TO_MERCHANT = 0.62;
/** Cash-out drains stop below ₹4,000 left (ATM chunking). */
const DRAIN_FLOOR_MINOR = 400_000;

export const rid = (p: string) => `${p}_${crypto.randomBytes(9).toString("hex")}`; // 72 random bits

const rand = (a: number, b: number) => a + Math.random() * (b - a);
const randInt = (a: number, b: number) => Math.floor(rand(a, b + 1));
const pick = <T,>(arr: T[]): T => arr[Math.floor(Math.random() * arr.length)];
/** Rupees generated by the simulator → integer paise (generation, not a legacy conversion). */
const paise = (rupees: number) => Math.max(1, Math.round(rupees * 100));

// Log-normal-ish everyday payment amount (₹20 – ₹6000, occasionally more)
function legitAmountMinor(): number {
  return paise(Math.round(Math.min(Math.exp(rand(3.2, 8.2)), 25_000)));
}

/** One payment the simulator wants to execute; the gate decides. */
export interface PaymentRequest {
  attemptId: string;
  txnId: string;
  fromId: string;
  toId: string;
  amountMinor: number;
  ts: number;
  /** ground-truth tag for live evaluation/feed only — never persisted */
  scenarioId?: string;
  channel: "BASE_LOAD" | "SCHEDULED";
}

interface Scheduled {
  at: number;
  req: Omit<PaymentRequest, "ts">;
}

export interface Scenario {
  id: string;
  pattern: Pattern;
  startedAt: number;
  muleIds: Set<string>;
  victimVpa: string;
  amountMinor: number;
}

export interface SimulatorOptions {
  runId: string;
  now: number;
  baseTps: number;
  nPeople?: number;
  nMerchants?: number;
}

export class Simulator {
  accounts = new Map<string, Account>();
  scenarios: Scenario[] = [];
  private people: string[] = [];
  private merchants: string[] = [];
  private queue: Scheduled[] = [];
  readonly runId: string;
  sinkId = "";
  baseTps: number;
  private store: Store;
  private truth: SimTruthRepository;

  constructor(store: Store, truth: SimTruthRepository, opts: SimulatorOptions) {
    this.store = store;
    this.truth = truth;
    this.runId = opts.runId;
    this.baseTps = opts.baseTps;
    const existing = store.accounts.listByRun(opts.runId);
    if (existing.length > 0) this.load(existing);
    else this.seed(opts.now, opts.nPeople ?? 12_000, opts.nMerchants ?? 300);
  }

  /** Resume a persisted run: same account ids, balances and holds. */
  private load(existing: LedgerAccount[]) {
    for (const a of existing) this.register({ id: a.id, vpa: a.vpa, name: a.name, createdAt: a.createdAt, kind: a.kind }, !!a.basePool);
  }

  private register(acc: Account, basePool: boolean) {
    this.accounts.set(acc.id, acc);
    if (acc.kind === "sink") this.sinkId = acc.id;
    else if (basePool && acc.kind === "person") this.people.push(acc.id);
    else if (basePool && acc.kind === "merchant") this.merchants.push(acc.id);
  }

  /** Create a fresh funded population in one transaction. */
  private seed(now: number, nPeople: number, nMerchants: number) {
    serialTx(this.store, () => {
      for (let i = 0; i < nPeople; i++) {
        // opening balances ≈ ₹5k – ₹4.4L, log-normal
        this.open(now - rand(30, 2000) * DAY_MS, "person", paise(Math.round(Math.exp(rand(8.5, 13)))), undefined, undefined, true);
      }
      for (let i = 0; i < nMerchants; i++) {
        const name = MERCHANTS[i % MERCHANTS.length];
        this.open(now - rand(200, 3000) * DAY_MS, "merchant", paise(Math.round(rand(200_000, 2_000_000))), name, `${name}@${pick(BANKS)}`, true);
      }
      this.open(0, "sink", 0, "ATM / cash-out", "cash@atm");
    });
  }

  /**
   * Open a funded account (the only way money enters a run). Only the
   * background population joins random base-load traffic (`basePool`);
   * scenario and demo accounts move money only on their schedule.
   */
  open(createdAt: number, kind: Account["kind"], openingMinor: number, name?: string, vpa?: string, basePool = false): Account {
    const n = name ?? `${pick(FIRST)}.${pick(LAST)}`;
    const acc: Account = { id: rid("acc"), vpa: vpa ?? `${n}${randInt(1, 99)}@${pick(BANKS)}`, name: n, createdAt, kind };
    this.store.accounts.upsert({ ...acc, balanceMinor: openingMinor, openingBalanceMinor: openingMinor, runId: this.runId, basePool });
    this.register(acc, basePool);
    return acc;
  }

  /** A mule account: usually freshly opened, sometimes an older rented account */
  private newMule(now: number, scenarioId: string, openingMinor = 0): Account {
    const ageDays = Math.random() < 0.75 ? rand(0.2, 6) : rand(30, 400);
    const acc = this.open(now - ageDays * DAY_MS, "person", openingMinor);
    this.truth.label(acc.id, scenarioId, true);
    return acc;
  }

  /** Queue a payment for execution at `at`; its attempt id is fixed now. */
  schedule(at: number, fromId: string, toId: string, amountMinor: number, scenarioId?: string): string {
    const attemptId = rid("att");
    this.queue.push({
      at,
      req: { attemptId, txnId: rid("tx"), fromId, toId, amountMinor: Math.max(1, Math.round(amountMinor)), scenarioId, channel: "SCHEDULED" },
    });
    return attemptId;
  }

  pendingCount(): number {
    return this.queue.length;
  }

  randomPeople(n: number): string[] {
    return Array.from({ length: n }, () => pick(this.people));
  }

  randomMerchant(): string {
    return pick(this.merchants);
  }

  /** A victim who can actually afford the transfer (no money is minted). */
  private pickVictim(amountMinor: number): { id: string; amountMinor: number } {
    let best = { id: this.people[0], balance: -1 };
    for (let i = 0; i < 400; i++) {
      const id = pick(this.people);
      const bal = this.store.accounts.get(id)?.balanceMinor ?? 0;
      if (bal >= amountMinor) return { id, amountMinor };
      if (bal > best.balance) best = { id, balance: bal };
    }
    return { id: best.id, amountMinor: Math.max(1, Math.floor(best.balance * 0.8)) };
  }

  launch(pattern: Pattern, now: number): Scenario {
    const id = rid("scn");
    const muleIds = new Set<string>();
    let amountMinor = 0;
    let victimId = "";
    // expected balance of each scenario account, so no mule is scheduled to
    // send more than it will actually have received
    const expected = new Map<string, number>();
    const credit = (acc: string, m: number) => expected.set(acc, (expected.get(acc) ?? 0) + m);
    const send = (at: number, from: string, to: string, m: number) => {
      const amt = Math.min(Math.round(m), expected.get(from) ?? Infinity);
      if (amt <= 0) return;
      if (expected.has(from)) expected.set(from, (expected.get(from) ?? 0) - amt);
      credit(to, amt);
      this.schedule(at, from, to, amt, id);
    };
    const drain = (from: string, start: number, share = 1) => {
      let remaining = Math.floor((expected.get(from) ?? 0) * share);
      let tt = start;
      while (remaining > DRAIN_FLOOR_MINOR) {
        const chunk = Math.min(remaining, paise(Math.round(rand(7000, 14000))));
        send(tt, from, this.sinkId, chunk);
        remaining -= chunk;
        tt += rand(4000, 8000);
      }
    };

    serialTx(this.store, () => {
      if (pattern === "fanout_layering") {
        const v = this.pickVictim(paise(Math.round(rand(150_000, 480_000))));
        victimId = v.id;
        amountMinor = v.amountMinor;
        const root = this.newMule(now, id);
        muleIds.add(root.id);
        send(now + 500, victimId, root.id, amountMinor);

        const l1 = Array.from({ length: randInt(5, 7) }, () => this.newMule(now, id));
        l1.forEach((m) => muleIds.add(m.id));
        const t = now + rand(2500, 4000);
        split(amountMinor, l1.length).forEach((share, i) => send(t + i * rand(200, 600), root.id, l1[i].id, share));

        const cashouts = Array.from({ length: randInt(2, 3) }, () => this.newMule(now, id));
        cashouts.forEach((m) => muleIds.add(m.id));
        l1.forEach((m) => {
          const l2s = Array.from({ length: randInt(2, 4) }, () => this.newMule(now, id));
          l2s.forEach((x) => muleIds.add(x.id));
          const shares = split(expected.get(m.id) ?? 0, l2s.length);
          const tt = t + rand(3000, 6000);
          l2s.forEach((x, j) => {
            send(tt + j * rand(150, 500), m.id, x.id, shares[j]);
            // layer 2 forwards to a cash-out account
            send(tt + rand(2500, 5000), x.id, pick(cashouts).id, shares[j] * rand(0.96, 1.0));
          });
        });
        // cash-outs drain to ATM in chunks over a minute+ (ATM limits are
        // real) — a hold mid-drain makes the remaining attempts get rejected
        cashouts.forEach((c) => drain(c.id, t + rand(9000, 12000)));
      }

      if (pattern === "circular_routing") {
        const v = this.pickVictim(paise(Math.round(rand(80_000, 200_000))));
        victimId = v.id;
        amountMinor = v.amountMinor;
        const loop = Array.from({ length: randInt(5, 7) }, () => this.newMule(now, id));
        loop.forEach((m) => muleIds.add(m.id));
        send(now + 500, victimId, loop[0].id, amountMinor);
        let t = now + 2500;
        let carried = amountMinor;
        for (let r = 0; r < 3; r++) {
          for (let i = 0; i < loop.length; i++) {
            carried = Math.floor(carried * rand(0.97, 0.995));
            send(t, loop[i].id, loop[(i + 1) % loop.length].id, carried);
            t += rand(800, 1600);
          }
        }
        drain(loop[0].id, t + 1000, 0.95);
      }

      if (pattern === "smurfing") {
        const aggregator = this.newMule(now, id);
        const cashA = this.newMule(now, id);
        const cashB = this.newMule(now, id);
        [aggregator, cashA, cashB].forEach((m) => muleIds.add(m.id));
        let t = now + 800;
        let total = 0;
        for (let i = 0, n = randInt(22, 32); i < n; i++) {
          const amt = paise(Math.round(rand(9000, 9950))); // just under the ₹10k reporting radar
          // each smurf is funded at account opening with exactly what it sends
          const s = this.newMule(now, id, amt);
          muleIds.add(s.id);
          credit(s.id, amt);
          send(t, s.id, aggregator.id, amt);
          total += amt;
          t += rand(250, 900);
        }
        amountMinor = total;
        send(t + 2000, aggregator.id, cashA.id, total * 0.55);
        send(t + 2600, aggregator.id, cashB.id, total * 0.43);
        drain(cashA.id, t + rand(6000, 8000), 0.9);
        drain(cashB.id, t + rand(6000, 8000), 0.9);
      }
    });

    const scenario: Scenario = {
      id,
      pattern,
      startedAt: now,
      muleIds,
      victimVpa: victimId ? (this.accounts.get(victimId)?.vpa ?? victimId) : "(many funded senders)",
      amountMinor,
    };
    this.scenarios.push(scenario);
    return scenario;
  }

  /**
   * Advance the clock: propose base-load payments plus any due scheduled ones.
   * Nothing is filtered here — held accounts are rejected by the gate.
   */
  pump(now: number, dtMs: number): PaymentRequest[] {
    const out: PaymentRequest[] = [];
    const n = Math.round((this.baseTps * dtMs) / 1000);
    for (let i = 0; i < n; i++) {
      const ts = Math.round(now - Math.random() * dtMs);
      const base = { attemptId: rid("att"), txnId: rid("tx"), amountMinor: legitAmountMinor(), ts, channel: "BASE_LOAD" as const };
      if (this.merchants.length && Math.random() < SETTLEMENT_SHARE) {
        out.push({ ...base, fromId: pick(this.merchants), toId: pick(this.people) });
        continue;
      }
      const fromId = pick(this.people);
      const toId = Math.random() < PERSON_TO_MERCHANT && this.merchants.length ? pick(this.merchants) : pick(this.people);
      if (toId === fromId) continue;
      out.push({ ...base, fromId, toId });
    }

    this.queue.sort((a, b) => a.at - b.at);
    while (this.queue.length && this.queue[0].at <= now) {
      const { req } = this.queue.shift()!;
      out.push({ ...req, ts: Math.round(now) });
    }
    // execution order = ledger order
    out.sort((a, b) => a.ts - b.ts);
    return out;
  }
}

/** Split an integer amount into n uneven integer parts that sum exactly to total */
function split(total: number, n: number): number[] {
  if (n <= 0) return [];
  const weights = Array.from({ length: n }, () => rand(0.6, 1.4));
  const sum = weights.reduce((a, b) => a + b, 0);
  const parts = weights.map((w) => Math.floor((total * w) / sum));
  parts[n - 1] += total - parts.reduce((a, b) => a + b, 0);
  return parts;
}
